// ─── Domain models ────────────────────────────────────────────────────────────

/** A chat session grouping all messages under a single conversation context.
 *  @param id               Unique session identifier (UUID).
 *  @param title            Human-readable session title.
 *  @param createdAt        ISO-8601 creation timestamp.
 *  @param updatedAt        ISO-8601 last-updated timestamp.
 *  @param model            LLM model name used for this session (e.g. "llama3.2").
 *  @param rootPath         Optional filesystem path set as the session working directory.
 *  @param lastResponseId   ID of the last Responses API response; used to thread stateful
 *                          multi-turn conversations across agent runs within the same session.
 */
case class Session(
    id:             String,
    title:          String,
    createdAt:      String,
    updatedAt:      String,
    model:          String,
    rootPath:       Option[String],
    lastResponseId: Option[String] = None
) derives ReadWriter

/** A single message in a session's conversation history.
 *  @param id          Unique message identifier (UUID).
 *  @param sessionId   Parent session identifier.
 *  @param role        Speaker role: [[MessageRole.User]], [[MessageRole.Assistant]], or [[MessageRole.System]].
 *  @param content     Text content of the message.
 *  @param timestamp   ISO-8601 timestamp of when the message was recorded.
 *  @param attachments List of attachment references (file paths or URIs); empty by default.
 */
case class Message(
    id: String,
    sessionId: String,
    role: MessageRole,
    content: String,
    timestamp: String,
    attachments: List[String] = Nil
) derives ReadWriter

/** A record of a single tool invocation within an agent turn.
 *  @param id         Unique run identifier (UUID).
 *  @param sessionId  Parent session identifier.
 *  @param tool       Name of the tool that was invoked.
 *  @param input      JSON-serialised input payload passed to the tool.
 *  @param output     JSON-serialised output returned by the tool.
 *  @param status     Outcome: [[RunStatus.Success]], [[RunStatus.Error]], or [[RunStatus.Cancelled]].
 *  @param traceId    Trace identifier linking the run to its agent turn.
 *  @param durationMs Wall-clock duration of the tool invocation in milliseconds.
 */
case class ToolRun(
    id: String,
    sessionId: String,
    tool: String,
    input: String,
    output: String,
    status: RunStatus,
    traceId: String,
    durationMs: Long
) derives ReadWriter

/** A session-scoped key-value memory entry persisted in SQLite.
 *  @param sessionId  Owning session identifier.
 *  @param key        Unique key within the session.
 *  @param value      Stored string value.
 *  @param updatedAt  ISO-8601 timestamp of the last write.
 */
case class MemoryEntry(
    sessionId: String,
    key:       String,
    value:     String,
    updatedAt: String
) derives ReadWriter

/**
 *  A single step within an agent turn's trajectory.
 *  @param stepType    [[StepType.Thinking]] — intermediate LLM response before tool calls;
 *                     [[StepType.ToolCall]] — a dispatched tool invocation.
 *  @param iteration   1-based iteration number this step belongs to.
 *  @param content     Intermediate LLM response text (thinking steps only; empty for tool_call).
 *  @param command     Raw command string (tool_call steps only; empty for thinking).
 *  @param result      Tool output text (tool_call steps only; empty for thinking).
 *  @param durationMs  Wall-clock duration in ms (tool_call only; 0 for thinking).
 */
case class AgentTurnStep(
    stepType:   StepType,
    iteration:  Int,
    content:    String,
    command:    String,
    result:     String,
    durationMs: Long
) derives ReadWriter

/**
 *  Complete trajectory record for one agent turn (user prompt → final answer).
 *  Stores all intermediate reasoning steps and tool calls so the UI can replay
 *  the full trajectory on history reload.
 *  @param id             Unique identifier (UUID).
 *  @param sessionId      Parent session identifier.
 *  @param userMsgId      [[Message]] id of the triggering user message.
 *  @param assistantMsgId [[Message]] id of the final assistant answer (empty if cancelled).
 *  @param steps          Ordered list of intermediate steps (thinking + tool_call).
 *  @param traceId        Trace identifier linking this turn to its log entries.
 *  @param timestamp      ISO-8601 timestamp of when the turn completed.
 */
case class AgentTurn(
    id:             String,
    sessionId:      String,
    userMsgId:      String,
    assistantMsgId: String,
    steps:          List[AgentTurnStep],
    traceId:        String,
    timestamp:      String
) derives ReadWriter

/** Token and latency accounting for a single LLM call.
 *  @param id                Unique record identifier (UUID).
 *  @param traceId           Trace identifier of the agent turn that triggered the call.
 *  @param sessionId         Parent session identifier.
 *  @param model             LLM model name used for the call.
 *  @param promptTokens      Number of tokens in the prompt sent to the model.
 *  @param completionTokens  Number of tokens in the model's response.
 *  @param latencyMs         End-to-end latency of the LLM call in milliseconds.
 *  @param createdAt         ISO-8601 timestamp of when the record was created.
 */
case class TokenUsage(
    id: String,
    traceId: String,
    sessionId: String,
    model: String,
    promptTokens: Int,
    completionTokens: Int,
    latencyMs: Long,
    createdAt: String
) derives ReadWriter
