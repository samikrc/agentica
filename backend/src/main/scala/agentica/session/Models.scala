package agentica.session

import upickle.default.*

// ─── Opaque types ─────────────────────────────────────────────────────────────

/**
 *  Type-safe wrapper for a message role.
 *  Prevents mixing up role strings with other [[String]] parameters at compile time.
 *  Runtime representation is a plain [[String]] with zero overhead.
 */
opaque type MessageRole = String

/**
 *  Companion providing constants, safe/unsafe constructors, and a [[ReadWriter]].
 */
object MessageRole
{
    /** Role for messages sent by the human user. */
    val User: MessageRole = "user"

    /** Role for messages generated by the AI assistant. */
    val Assistant: MessageRole = "assistant"

    /** Role for the system prompt injected at context assembly. */
    val System: MessageRole = "system"

    /**
     *  Parses a role string from an external source (HTTP parameter, SQLite row).
     *  @param s  Raw string value.
     *  @return   `Some(role)` for recognised values; `None` for unknown strings.
     */
    def fromString(s: String): Option[MessageRole] = s match
    {
        case "user" | "assistant" | "system" => Some(s)
        case _                               => None
    }

    /**
     *  Wraps a string without validation.
     *  Use only for data from trusted sources (e.g. rows already validated on write).
     *  @param s  Raw string value to wrap.
     *  @return   The wrapped [[MessageRole]].
     */
    def unsafe(s: String): MessageRole = s

    extension (r: MessageRole)
    {
        /** Returns the underlying string value for JDBC writes and JSON serialisation. */
        def value: String = r
    }

    /** upickle [[ReadWriter]] — delegates to the underlying [[String]] serialiser. */
    given ReadWriter[MessageRole] = summon[ReadWriter[String]].asInstanceOf[ReadWriter[MessageRole]]
}

